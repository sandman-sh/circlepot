import { mkdir, readFile, writeFile } from 'node:fs/promises'
import solc from 'solc'

const source = await readFile(new URL('../contracts/CirclePot.sol', import.meta.url), 'utf8')
const input = {
  language: 'Solidity',
  sources: { 'CirclePot.sol': { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 300 },
    viaIR: true,
    evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
}
const output = JSON.parse(solc.compile(JSON.stringify(input)))
const errors = (output.errors ?? []).filter((entry) => entry.severity === 'error')
if (errors.length) {
  for (const error of errors) console.error(error.formattedMessage)
  process.exit(1)
}
const contract = output.contracts['CirclePot.sol'].CirclePot
await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true })
const artifact = {
  contractName: 'CirclePot',
  compiler: solc.version(),
  abi: contract.abi,
  bytecode: `0x${contract.evm.bytecode.object}`,
}
await writeFile(
  new URL('../src/generated/circlePotArtifact.ts', import.meta.url),
  `// Generated by npm run compile:contract. Do not edit by hand.\nexport const circlePotAbi = ${JSON.stringify(contract.abi, null, 2)} as const\nexport const circlePotBytecode = '${artifact.bytecode}' as const\n`,
)
await writeFile(new URL('../src/generated/circlePotArtifact.json', import.meta.url), `${JSON.stringify(artifact, null, 2)}\n`)
console.log(`Compiled CirclePot (${contract.evm.bytecode.object.length / 2} byte creation code) with solc ${solc.version()}`)
